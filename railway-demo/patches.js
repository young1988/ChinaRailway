/* 线路补丁（管理员维护）
   ------------------------------------------------------------------
   用途：OSM 里某些区段确实没有铁路数据，导致线路断开、行程追踪被直线桥接。
   管理员可在?admin=1 管理模式下拾取缺口两端生成补丁，粘到本文件提交仓库，
   所有用户即可受益。诊断工具 tools/diagnose_gaps.py 产出的「真缺口」清单
   （当前 23 条）是待补的权威列表。

   补丁类型
   ------------------------------------------------------------------
   1) connect —— 在两点之间补一段路径（最常用）
      {
        id: 'wunhe-line',          // 唯一标识，便于后续更新/停用
        type: 'connect',
        line: '五女山—通化',// 备注用：这条补丁补的是哪条线
        a: [41.7756, 125.9158],     // 端点 A [纬度, 经度]
        b: [41.8, 125.9],           // 端点 B
        via: [[41.78, 125.91]],     // 可选：途经点（折线）。不给就是两点直线
        kind: 'conventional'        // 可选：'highspeed' | 'conventional'，决定着色与吸附类型
      }

   2) replace —— 覆盖某条线某一段的几何（v1 暂未在界面开放，预留给复杂场景）
      { id, type: 'replace', line, index: 0, polylines: [[ [lat,lon], ... ]] }

   字段说明
   ------------------------------------------------------------------
   - a / b 建议直接用 diagnose_gaps.py 输出的坐标（缺口两端的最优点）。
   - kind 缺省按 'conventional' 处理；若补的是高铁段请显式写 'highspeed'，
     否则会按普速着色、并在迷雾地图里被算成"未走过的普速"。
   - 想停用某条补丁，把enabled 改成 false（保留记录便于追溯）。

   合并规则
   ------------------------------------------------------------------
   仓库补丁（本文件）与用户本地补丁（?admin=1 存在浏览器 localStorage，
   键 RW_PATCHES_LOCAL）会合并，本地补丁按 id 覆盖仓库补丁。
   connect 补丁会被追加成目标线的一条新 polyline，因此：
     ·渲染时它与原线同色，看起来就是线路接上了；
     · 走线追踪（Net.build）会把它加进全路网图，缺口两端由此连通。
   注意：只补 <= BRIDGE_KM(6km) 以外的缺口才有意义，6km 以内的缺口
   Net.bridgeComponents 已自动搭桥，无需补丁。
*/
